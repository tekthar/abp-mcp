const REDACTED = "[REDACTED]";

// Shorter values are too likely to collide with ordinary text to replace wherever they occur as a substring.
const MIN_SECRET_LENGTH = 6;

const BEARER = /(Bearer\s+)[A-Za-z0-9\-._~+/]+=*/gi;
const FORM_SECRET = /\b(access_token|refresh_token|id_token|password|client_secret|code|code_verifier|token)=([^&\s"']+)/gi;
const JSON_SECRET = /("(?:access_token|refresh_token|id_token|password|client_secret|code|code_verifier)"\s*:\s*")([^"]*)(")/gi;

/**
 * Removes secrets from anything the bridge writes to a log. Every token, password, authorization code and
 * client secret is registered as soon as the bridge sees it; known secret-bearing shapes (bearer headers,
 * form fields, JSON fields) are masked even when a value was never registered.
 */
export class Redactor {
  private readonly secrets = new Set<string>();
  private readonly shortCredentials = new Map<string, RegExp>();

  /**
   * Remember a secret the bridge came across (a token, a code, a verifier) so every later log line masks it.
   * Ignores empty and very short values: those are generated by servers, so a short one is not a real secret.
   */
  add(secret: string | null | undefined): void {
    if (secret && secret.length >= MIN_SECRET_LENGTH) {
      this.secrets.add(secret);
    }
  }

  /**
   * Remember a credential the user supplied (a password or a client secret), whatever its length. A value of
   * six characters or more is masked wherever it appears. A shorter one is masked wherever it stands on its
   * own (not inside a longer run of letters and digits), so the password "abc" is masked in
   * "password 'abc' rejected" without turning every word that contains "abc" into noise.
   */
  addCredential(secret: string | null | undefined): void {
    if (!secret) {
      return;
    }

    if (secret.length >= MIN_SECRET_LENGTH) {
      this.secrets.add(secret);
    } else if (!this.shortCredentials.has(secret)) {
      const escaped = secret.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
      this.shortCredentials.set(secret, new RegExp(`(?<![A-Za-z0-9])${escaped}(?![A-Za-z0-9])`, "g"));
    }
  }

  /** The text with every registered secret and secret-bearing field masked. */
  redact(text: string): string {
    let result = text;
    for (const secret of this.secrets) {
      result = result.split(secret).join(REDACTED);
    }

    for (const pattern of this.shortCredentials.values()) {
      result = result.replace(pattern, REDACTED);
    }

    return result
      .replace(BEARER, `$1${REDACTED}`)
      .replace(FORM_SECRET, `$1=${REDACTED}`)
      .replace(JSON_SECRET, `$1${REDACTED}$3`);
  }
}
